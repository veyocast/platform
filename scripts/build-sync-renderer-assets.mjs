import { createHash } from "node:crypto";
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { join } from "node:path";
const root = fileURLToPath(new URL("../", import.meta.url));
const source = join(
  root,
  "docs/sync-v1-rebuild/handoff/reference/sites-sync/public/assets",
);
const mime = {
  ".svg": "image/svg+xml",
  ".png": "image/png",
  ".webp": "image/webp",
  ".woff2": "font/woff2",
  ".ttf": "font/ttf",
};
const files = readdirSync(source, { withFileTypes: true })
  .filter((entry) => entry.isFile())
  .flatMap((entry) => {
    const extension = entry.name.slice(entry.name.lastIndexOf("."));
    if (!mime[extension]) return [];
    const bytes = readFileSync(join(source, entry.name)),
      deployed = readFileSync(
        join(root, "apps/control/public/assets", entry.name),
      );
    if (!bytes.equals(deployed))
      throw Error(`Source renderer asset differs: ${entry.name}`);
    return [
      {
        path: "/assets/" + entry.name,
        sha256: createHash("sha256").update(bytes).digest("hex"),
        bytes: bytes.length,
        mimeType: mime[extension],
      },
    ];
  })
  .sort((a, b) => a.path.localeCompare(b.path, "en"));
if (files.length !== 11)
  throw Error(
    `Expected all 11 Source renderer images/fonts; found ${files.length}`,
  );
writeFileSync(
  join(root, "packages/contracts/src/sync-system-assets.ts"),
  "// Generated by scripts/build-sync-renderer-assets.mjs from the immutable Sync handoff.\nexport const syncSystemAssets = " +
    JSON.stringify(files, null, 2) +
    " as const;\n",
);
process.stdout.write(
  JSON.stringify({
    verifiedRendererAssets: files.length,
    archivesIncluded: 0,
  }) + "\n",
);
