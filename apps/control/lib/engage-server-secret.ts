import "server-only";

import { createHmac } from "node:crypto";

type Environment = Record<string, string | undefined>;

/** Keep an explicit Engage key stable; derive a separate key for existing deployments. */
export function readEngageAbuseSigningSecret(environment: Environment = process.env) {
  const dedicated = environment.ENGAGE_ABUSE_SIGNING_SECRET;
  if (dedicated !== undefined) {
    if (dedicated.trim().length < 32) throw new Error("Engage-beveiligingsconfiguratie is ongeldig.");
    return dedicated;
  }
  // This is the explicit, persistent runtime key required by our deployment
  // health gate, never a temporary key generated by the Next build.
  const root = environment.NEXT_SERVER_ACTIONS_ENCRYPTION_KEY;
  if (!root || root.trim().length < 32) throw new Error("Engage-beveiligingsconfiguratie ontbreekt.");
  return createHmac("sha256", root).update("veyocast:engage:voter-identity:v1").digest("hex");
}
