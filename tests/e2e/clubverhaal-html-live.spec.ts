function sql(value: string) { return execFileSync('docker', ['exec', container!, 'psql', '-U', 'postgres', '-d', 'postgres', '-X', '-v', 'ON_ERROR_STOP=1', '-At', '-c', value], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'], timeout: 30000 }).trim(); }
function query<T>(value: string): T { return JSON.parse(sql(value)) as T; }
function command(value: string) { return sql(`begin;set local role authenticated;set local request.jwt.claims='{"sub":"${actor}","role":"authenticated","aal":"aal2"}';${value}commit;`); }
async function authenticate(page: Page) {
    sql(`delete from auth.mfa_factors where user_id='${actor}';`);
    await page.goto("/login");
    await page.getByLabel("E-mailadres").fill("pilot-admin@veyocast.test");
    await page.getByLabel("Wachtwoord").fill("veyocast-local");
    await page.getByRole("button", { name: "Doorgaan" }).click();
    await expect(page).toHaveURL(/\/context/);
    await page.getByRole("button", { name: "Open vereniging" }).click();
    await expect(page).toHaveURL(/\/dashboard$/);
    await page.goto("/auth/mfa");
    await page.getByLabel("Naam van authenticator").fill("Sites original media workflows");
    await page.getByRole("button", { name: "Nieuwe authenticator toevoegen" }).click();
    await page.getByText("Handmatige sleutel tonen").click();
    const secret = (await page.locator(".mfa-secret").textContent())!.trim();
    const bits = [...secret.replace(/=|\s/g, "").toUpperCase()].map(character => "ABCDEFGHIJKLMNOPQRSTUVWXYZ234567".indexOf(character).toString(2).padStart(5, "0")).join("");
    const key = Buffer.from(bits.match(/.{8}/g)!.map(byte => Number.parseInt(byte, 2)));
    const counter = Buffer.alloc(8);
    counter.writeBigUInt64BE(BigInt(Math.floor(Date.now() / 30000)));
    const digest = createHmac("sha1", key).update(counter).digest();
    const offset = digest.at(-1)! & 15;
    await page.getByLabel("Zescijferige code").fill(String((digest.readUInt32BE(offset) & 0x7fffffff) % 1000000).padStart(6, "0"));
    await page.getByRole("button", { name: "Authenticator verifiëren" }).click();
    await expect(page).toHaveURL(/\/dashboard$/);
}
